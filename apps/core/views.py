def robots_txt(request):
    sitemap_url = public_absolute_url(reverse("sitemap"), request=request)
    lines = [
        "User-agent: *",
        "Allow: /",
        "Disallow: /admin/",
        "Disallow: /office/",
        "Disallow: /client/",
        "Disallow: /accounts/",
        "Disallow: /messenger/",
        "Disallow: /billing/",
        "Disallow: /integrations/",
        "Disallow: /template-demos/",
        f"Sitemap: {sitemap_url}",
    ]
    return HttpResponse("\n".join(lines) + "\n", content_type="text/plain; charset=utf-8")


def sitemap_xml(request):
    today = timezone.now().date().isoformat()
    urls = [
        (reverse("home"), "weekly", "1.0"),
        (reverse("content:services"), "weekly", "0.9"),
        (reverse("content:templates"), "weekly", "0.9"),
        (reverse("content:reviews"), "monthly", "0.7"),
        (reverse("public-brief"), "monthly", "0.8"),
    ]
    urls.extend((reverse("legal-page", kwargs={"slug": slug}), "monthly", "0.4") for slug in LEGAL_PAGES)
    urls.extend((reverse("fast-legal-page", kwargs={"slug": slug}), "monthly", "0.3") for slug in FAST_LEGAL_PAGES)
    urls.extend((service.get_absolute_url(), "monthly", "0.7") for service in Service.objects.filter(is_published=True))

    entries = []
    for path, changefreq, priority in urls:
        entries.append(
            "\n".join(
                [
                    "  <url>",
                    f"    <loc>{public_absolute_url(path, request=request)}</loc>",
                    f"    <lastmod>{today}</lastmod>",
                    f"    <changefreq>{changefreq}</changefreq>",
                    f"    <priority>{priority}</priority>",
                    "  </url>",
                ]
            )
        )
    xml = "\n".join(
        [
            '<?xml version="1.0" encoding="UTF-8"?>',
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
            *entries,
            "</urlset>",
        ]
    )
    return HttpResponse(xml, content_type="application/xml; charset=utf-8")


