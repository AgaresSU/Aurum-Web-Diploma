def client_safe_text(value):
    if not isinstance(value, str):
        return value
    result = value
    for source, replacement in CLIENT_TEXT_REPLACEMENTS:
        result = result.replace(source, replacement)
    return (
        " ".join(result.split())
        if "\n" not in result
        else "\n".join(" ".join(line.split()) for line in result.splitlines())
    )


def client_safe_object(item, fields):
    cleaned = copy(item)
    for field in fields:
        if hasattr(cleaned, field):
            setattr(cleaned, field, client_safe_text(getattr(cleaned, field)))
    return cleaned


def client_safe_tree(value):
    if isinstance(value, str):
        return client_safe_text(value)
    if isinstance(value, list):
        return [client_safe_tree(item) for item in value]
    if isinstance(value, tuple):
        return tuple(client_safe_tree(item) for item in value)
    if isinstance(value, dict):
        return {key: client_safe_tree(item) for key, item in value.items()}
    return value


def client_safe_category_filters(categories):
    return [{"value": category, "label": client_safe_text(category)} for category in categories]


def clean_service(service):
    return client_safe_object(
        service,
        (
            "title",
            "short_description",
            "full_description",
            "business_value",
            "price_note",
            "deliverables",
        ),
    )


